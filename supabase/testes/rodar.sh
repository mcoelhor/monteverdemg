#!/usr/bin/env bash
# Recria um banco local do zero (estrutura de produção + migrações novas) e roda os testes SQL.
# Uso: PGHOST=/tmp PGPORT=54329 supabase/testes/rodar.sh
# Requer: Postgres 16 local com superusuário "postgres". Usa só dados fictícios.
set -euo pipefail
cd "$(dirname "$0")/.."
export PGUSER=${PGUSER:-postgres} PGHOST=${PGHOST:-/tmp} PGPORT=${PGPORT:-54329}
DB=${DB:-mv_teste}
psql -q -d postgres -c "drop database if exists $DB" -c "create database $DB"
run() { psql -q -X -v ON_ERROR_STOP=1 -d "$DB" "$@"; }

run -f testes/00_stub_supabase.sql
# O dump de tabelas está em ordem alfabética; as referenciadas precisam vir antes.
python3 testes/ordenar_tabelas.py banco/01_tabelas.sql > /tmp/01_ordenado.sql
run -f /tmp/01_ordenado.sql
# Em produção os ids destas tabelas são identity (o catálogo não mostra default)
run -c "alter table public.interactions alter column id add generated by default as identity; alter table public.leads alter column id add generated by default as identity;"
run -f banco/02_funcoes.sql
# Reproduz exatamente os grants de produção (o dump 03 lista o estado real)
run -c "revoke all on all tables in schema public from anon, authenticated;"
run -f banco/03_rls_grants_triggers_storage_cron.sql

if [ "${SEM_MIGRACOES:-0}" != "1" ]; then
  for m in migrations/*.sql; do
    case "$m" in *_rollback.sql) continue ;; esac
    echo "== migração $m"; run -f "$m"
  done
fi

falhas=0
for t in testes/t_*.sql; do
  echo "== teste $t"
  if run -f "$t"; then echo "   OK"; else echo "   FALHOU"; falhas=$((falhas+1)); fi
done

if [ "${TESTAR_ROLLBACK:-0}" = "1" ]; then
  for m in $(ls migrations/*_rollback.sql | sort -r); do echo "== rollback $m"; run -f "$m"; done
  echo "rollback aplicado sem erro"
fi
echo "falhas: $falhas"
exit $falhas
